#!/bin/sh
# Общие вспомогательные функции для CGI-скриптов invnet.

urldecode() {
  # printf '%s' вместо echo: значение, начинающееся с -n/-e, busybox-echo съел бы как опцию.
  printf '%b' "$(printf '%s' "$1" | sed 's/+/ /g; s/%\([0-9A-Fa-f][0-9A-Fa-f]\)/\\x\1/g')"
}

# CSRF-заслон для эндпоинтов, меняющих состояние. Панель без аутентификации (известный пункт
# бэклога), поэтому единственная защита от чужой страницы в LAN, дёргающей наши CGI, —
# доказательство того, что запрос пришёл из самой панели.
#
# Требуем ХОТЯ БЫ ОДИН положительный признак. Прежняя версия работала наоборот — «заголовка
# нет, значит свои», — и это обходилось тривиально: Origin браузер для GET-подресурсов не шлёт
# вообще, а Referer чужая страница убирает одной строкой:
#     <meta name="referrer" content="no-referrer">
# В итоге обычный <img src="http://192.168.7.1:8888/cgi-bin/stop"> с любого сайта в сети гасил
# все туннели, а <img ...connect?name=X&on=0> выключал профиль. Ответ атакующий не прочитает
# (CORS), но слепая запись проходила.
#
#   X-Invnet — ставит только наш fetch. Ни <img>, ни <form>, ни навигация заголовки задавать
#              не умеют, а кросс-origin fetch с кастомным заголовком уходит в preflight,
#              на который мы не отвечаем разрешением. Это основной признак.
#   Origin   — шлётся любым кросс-origin запросом; несовпадение = отказ немедленно.
#   Referer  — same-origin fetch шлёт его по умолчанию. Оставлен, чтобы панель, поднятая из
#              браузерного кэша до обновления, продолжала работать.
#
# Сравнение через [ = ], а не через case: $HTTP_HOST внутри шаблона case является ГЛОБОМ,
# и заголовок вида `Host: *` дал бы шаблон, матчащий любой Origin.
csrf_guard() {
  _h="$HTTP_HOST"
  _ok=0
  [ -n "$HTTP_X_INVNET" ] && _ok=1

  if [ -n "$HTTP_ORIGIN" ]; then
    if [ "$HTTP_ORIGIN" = "http://$_h" ] || [ "$HTTP_ORIGIN" = "https://$_h" ]; then
      _ok=1
    else
      printf '{"error":"origin"}\n'; exit 0
    fi
  fi

  if [ -n "$HTTP_REFERER" ]; then
    _rok=0
    for _p in "http://$_h" "https://$_h"; do
      _rest=${HTTP_REFERER#"$_p"}                     # кавычки внутри ${#} гасят глоббинг
      if [ "$_rest" != "$HTTP_REFERER" ]; then
        case "$_rest" in ''|/*) _rok=1 ;; esac        # ровно хост либо хост со слешем далее
      fi
    done
    if [ "$_rok" = 1 ]; then _ok=1
    else printf '{"error":"origin"}\n'; exit 0; fi
  fi

  [ "$_ok" = 1 ] || { printf '{"error":"origin"}\n'; exit 0; }
}
